#!/usr/bin/env bash
# =====================================================================
# installateur NERCEL v10.0 (autonome — fichier unique)
# L'archive nercel-10.0.tar.gz est embarquée à la fin (base64).
# Dépendances : Python 3.8+. Optionnels : git, node/npm (scaffolds JS),
#               ollama (IA 100% locale — sinon fallback cloud sans clé).
#
#   bash installateur-nercel-v10.sh            # extrait + lance
#   bash installateur-nercel-v10.sh --open     # idem + ouvre le navigateur
#   bash installateur-nercel-v10.sh --stop     # arrêt
#   bash installateur-nercel-v10.sh --status   # état
#   bash installateur-nercel-v10.sh --restart  # redémarrer
# =====================================================================
set -u

ARCHIVE_NAME="nercel-10.0.tar.gz"
INSTALL_DIR="${NERCEL_INSTALL_DIR:-$HOME/nercel-10.0}"
DATA_DIR="${NERCEL_DATA:-$HOME/.nercel}"
SELF="$(readlink -f "$0")"
PAYLOAD_MARKER="__NERCEL_V10_PAYLOAD__"

G=$'\033[0;32m'; R=$'\033[0;31m'; C=$'\033[0;36m'; B=$'\033[1m'; N=$'\033[0m'
ok(){   printf "${G}✓${N} %s\n" "$*"; }
err(){  printf "${R}✗ %s${N}\n" "$*" >&2; }
info(){ printf "${C}▸${N} %s\n" "$*"; }
banner(){ printf "\n${B}${C}▲ NERCEL${N} ${B}v10.0 — le monstre du développement${N}\n\n"; }

PY=""
for c in python3 python; do
  if command -v "$c" >/dev/null 2>&1 && "$c" -c 'import sys;sys.exit(0 if sys.version_info>=(3,8) else 1)' 2>/dev/null; then
    PY="$c"; break
  fi
done
port_up(){ "$PY" -c "import socket,sys;s=socket.socket();s.settimeout(0.5);sys.exit(0 if s.connect_ex(('127.0.0.1', $1))==0 else 1)" 2>/dev/null; }

case "${1:-}" in
  --stop|--status|--restart)
    [ -z "$PY" ] && { err "Python 3.8+ requis"; exit 1; }
    if [ -x "$INSTALL_DIR/start.sh" ]; then
      exec bash "$INSTALL_DIR/start.sh" "$1"
    else
      for f in "$DATA_DIR/nercel.pid" "$DATA_DIR/nexusd.pid"; do
        [ -f "$f" ] && kill "$(cat "$f" 2>/dev/null)" 2>/dev/null && rm -f "$f"
      done
      pkill -f "server\.py" 2>/dev/null; pkill -f "nexusd\.py" 2>/dev/null
      ok "NERCEL arrêté"; exit 0
    fi
    ;;
esac

banner

[ "$(id -u)" = "0" ] && { err "Ne lance pas NERCEL en root."; exit 1; }
[ -z "$PY" ] && { err "Python 3.8+ requis (apt install python3)"; exit 1; }

SRC=""
TMP_TAR=""
if grep -q "^${PAYLOAD_MARKER}$" "$SELF" 2>/dev/null; then
  info "Extraction de la payload embarquée…"
  TMP_TAR="$(mktemp -t nercel10.XXXXXX.tar.gz)"
  if ! sed -n "/^${PAYLOAD_MARKER}$/,\$p" "$SELF" | tail -n +2 | base64 -d > "$TMP_TAR" 2>/dev/null; then
    err "Échec du décodage de la payload."; rm -f "$TMP_TAR"; exit 1
  fi
  SRC="$TMP_TAR"
else
  for d in "$(dirname "$SELF")" "$HOME/Bureau" "$HOME/Desktop" \
           "$HOME/Téléchargements" "$HOME/Downloads" "$HOME" "$PWD"; do
    [ -f "$d/$ARCHIVE_NAME" ] && { SRC="$d/$ARCHIVE_NAME"; break; }
  done
fi
[ -z "$SRC" ] && { err "Aucune payload et archive '$ARCHIVE_NAME' introuvable."; exit 1; }
ok "Archive prête ($(du -h "$SRC" | cut -f1))"
[ -n "$TMP_TAR" ] && trap 'rm -f "$TMP_TAR"' EXIT

command -v tar >/dev/null 2>&1 || { err "tar manquant"; exit 1; }
rm -rf "$INSTALL_DIR"; mkdir -p "$INSTALL_DIR"
if ! tar -xzf "$SRC" -C "$INSTALL_DIR" --strip-components=1; then
  err "Échec de l'extraction."; exit 1
fi
for f in start.sh server.py nexusd.py config.py aihub.py scaffolds.py devops.py nercel index.html app.js style.css docs.html; do
  [ -f "$INSTALL_DIR/$f" ] || { err "Fichier manquant : $f"; exit 1; }
done
chmod +x "$INSTALL_DIR/start.sh" "$INSTALL_DIR/nercel" "$INSTALL_DIR/server.py" "$INSTALL_DIR/nexusd.py" 2>/dev/null
ok "Extrait dans : $INSTALL_DIR"

MISSING=""
command -v git >/dev/null 2>&1 || MISSING="$MISSING git(GitHub désactivé)"
command -v node >/dev/null 2>&1 || MISSING="$MISSING node(scaffolds JS limités)"
command -v ollama >/dev/null 2>&1 || MISSING="$MISSING ollama(IA locale — fallback cloud sans clé actif)"
[ -n "$MISSING" ] && printf "${C}▸${N} optionnels absents :%s\n" "$MISSING"

info "Lancement…"
EXTRA=""; [ "${1:-}" = "--open" ] && EXTRA="--open"
bash "$INSTALL_DIR/start.sh" $EXTRA
exit 0
